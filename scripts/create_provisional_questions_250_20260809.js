function main() {
  ensureDataDir();
  const questions = GROUPS.flatMap(([category, items]) => items.map((question) => ({ category, question })));
  if (questions.length !== 250) throw new Error(`Expected 250 questions, got ${questions.length}`);

  const existingFiles = [
    path.join(DATA_DIR, 'upload_questions_200.xlsx'),
    path.join(DATA_DIR, 'questions_2000.xlsx'),
  ];
  const existing = existingFiles.flatMap((file) => readWorkbookRows(file))
    .map((row) => row.generated_question || row.question || '')
    .filter(Boolean);
  const existingKeys = new Set(existing.map(normalizeText));
  const draftKeys = new Set();

  const exactConflicts = [];
  for (const { question } of questions) {
    const key = normalizeText(question);
    if (draftKeys.has(key) || existingKeys.has(key)) exactConflicts.push(question);
    draftKeys.add(key);
  }
  if (exactConflicts.length) throw new Error(`Exact duplicates found:\n${exactConflicts.join('\n')}`);

  const rows = questions.map(({ category, question }, index) => {
    let nearestQuestion = '';
    let nearestSimilarity = 0;
    for (const candidate of existing) {
      const score = similarity(question, candidate);
      if (score > nearestSimilarity) {
        nearestQuestion = candidate;
        nearestSimilarity = score;
      }
    }
    return {
      no: START_NO + index,
      review_status: '검토 전',
      category,
      intent: `PROVISIONAL-${String(index + 1).padStart(3, '0')}`,
      test_focus: category,
      generated_question: question,
      expected_answer: '',
      nearest_existing_similarity: Number(nearestSimilarity.toFixed(4)),
      nearest_existing_question: nearestQuestion,
    };
  });

  const xlsxPath = path.join(DATA_DIR, `${OUTPUT_BASE}.xlsx`);
  const csvPath = path.join(DATA_DIR, `${OUTPUT_BASE}.csv`);
  writeWorkbook(xlsxPath, { provisional_questions: rows });
  writeCsv(csvPath, rows);

  const maxSimilarity = Math.max(...rows.map((row) => row.nearest_existing_similarity));
  const highSimilarity = rows.filter((row) => row.nearest_existing_similarity >= 0.8).length;
  console.log(`generated: ${rows.length}`);
  console.log(`number range: ${rows[0].no}-${rows.at(-1).no}`);
  console.log(`categories: ${GROUPS.length}`);
  console.log(`exact duplicates: ${exactConflicts.length}`);
  console.log(`similarity >= 0.8: ${highSimilarity}`);
  console.log(`max similarity: ${maxSimilarity}`);
  console.log(`xlsx: ${xlsxPath}`);
  console.log(`csv: ${csvPath}`);
}

main();
